"""Tests for act.py: the plan's action → module call → JSON outcome."""

import json
import re

import pytest

from release_automation.scripts import act as act_mod
from release_automation.scripts import draft_release
from release_automation.scripts.act import act, snapshot_outcome
from release_automation.scripts.commands import COMMANDS, JOB_ACT
from release_automation.tests.fake_github import REPO_URL, FakeGitHub, gh_error

SNAPSHOT = "release-snapshot/r1.4-abc1234"
REVIEW = "release-review/r1.4-abc1234"
CHANGELOG = "# r1.4\n\n## Release Notes\n\nNotes.\n\n<!-- BEGIN:AUTOGENERATED:CANDIDATE_CHANGES -->\nx\n<!-- END:AUTOGENERATED:CANDIDATE_CHANGES -->\n"
METADATA = "repository:\n  release_tag: r1.4\n  release_date: null\n"
MERGE_EVENT = {"pull_request": {"number": 41, "html_url": f"{REPO_URL}/pull/41"}}


@pytest.fixture(autouse=True)
def no_sleep(monkeypatch):
    monkeypatch.setattr(draft_release, "_sleep", lambda s: None)


def plan(action, **kw):
    return {
        "action": action,
        "trigger_type": "slash_command",
        "command": action,
        "release_tag": "r1.4",
        "state": "snapshot-active",
        "release_type": "pre-release-rc",
        "publish_mode": "draft",
        "issue_number": "40",
        "snapshot_branch": SNAPSHOT,
        "release_review_branch": REVIEW,
        "release_pr_number": "41",
        "release_issue_number": "40",
        "src_commit_sha": "abc1234def",
        "base_context": {"release_tag": "r1.4", "state": "snapshot-active"},
        **kw,
    }


def repo(**kw):
    return FakeGitHub(
        files={(SNAPSHOT, "CHANGELOG/CHANGELOG-r1.md"): CHANGELOG, (SNAPSHOT, "release-metadata.yaml"): METADATA},
        branches={SNAPSHOT: "s1", REVIEW: "v1"},
        **kw,
    )


def test_discard_snapshot():
    gh = repo()

    assert act(plan("discard-snapshot"), gh, {}) == {
        "action": "discard-snapshot",
        "success": "true",
        "error_message": "",
        "renamed_review_branch": f"{REVIEW}-preserved",
    }
    assert gh.closed_prs == [41]


def test_delete_draft_failure_outcome():
    gh = repo()
    del gh.branches[SNAPSHOT]

    outcome = act(plan("delete-draft", state="draft-ready"), gh, {})

    assert outcome == {
        "action": "delete-draft",
        "success": "false",
        "error_message": f"Snapshot branch {SNAPSHOT} not found",
        "renamed_review_branch": "",
    }


def test_publish_release():
    gh = repo(releases=[{"id": 7, "tag": "r1.4", "target": SNAPSHOT, "draft": True, "prerelease": True, "html_url": "u"}])

    outcome = act(plan("publish-release", state="draft-ready"), gh, {})

    assert outcome == {
        "action": "publish-release",
        "success": "true",
        "release_url": f"{REPO_URL}/releases/tag/r1.4",
        "reference_tag": "source/r1.4",
        "pointer_branch": "pre-release/r1.4",
        "error_message": "",
    }


def test_create_draft_posts_draft_created():
    gh = repo()

    outcome = act(plan("create-draft", trigger_type="pr_merge", command="", issue_number=""), gh, MERGE_EVENT)

    url = gh.releases[0]["html_url"]
    assert outcome == {
        "action": "create-draft",
        "success": "true",
        "draft_release_url": url,
        "candidate_block_stripped": "true",
        "error_message": "",
    }
    comment = gh.comments[0]
    assert comment["issue"] == 40
    assert comment["body"].startswith("<!-- release-bot:r1.4 -->\n**📦 Draft release created — State: `draft-ready`**")
    assert f"Triggered by merge of [Release PR #41]({REPO_URL}/pull/41)." in comment["body"]
    assert f"**Draft release:** [`r1.4`]({url})" in comment["body"]
    assert "Release notes cleaned (candidate block removed)." in comment["body"]


def test_create_draft_without_release_issue_posts_nothing():
    gh = repo()

    outcome = act(plan("create-draft", trigger_type="pr_merge", release_issue_number=""), gh, MERGE_EVENT)

    assert outcome["success"] == "true" and gh.comments == []


def test_draft_created_comment_failure_is_flagged(capsys):
    gh = repo(fail={"create_comment": [gh_error("HTTP 502")]})

    outcome = act(plan("create-draft", trigger_type="pr_merge"), gh, MERGE_EVENT)

    assert outcome["success"] == "true" and outcome["comment_failed"] == "true"
    assert "::error::Could not post draft_created: gh command failed: HTTP 502" in capsys.readouterr().out


def test_failed_draft_posts_no_comment():
    gh = repo(fail={"create_release": [gh_error("HTTP 422")]})

    outcome = act(plan("create-draft", trigger_type="pr_merge"), gh, MERGE_EVENT)

    assert outcome["success"] == "false" and gh.comments == []


def test_publish_on_merge():
    gh = repo()

    outcome = act(plan("publish-on-merge", trigger_type="pr_merge", publish_mode="on_merge"), gh, MERGE_EVENT)

    assert outcome["action"] == "publish-on-merge" and outcome["success"] == "true"
    assert outcome["release_url"] == f"{REPO_URL}/releases/tag/r1.4"
    assert not gh.releases[0]["draft"]
    assert gh.comments == []


def test_reopen_issue():
    gh = repo()

    outcome = act(plan("reopen-issue", trigger_type="issue_close", command=""), gh, {})

    assert outcome == {"action": "reopen-issue", "success": "true", "action_taken": "reopened", "error_message": ""}
    assert gh.reopened == [40]


def test_release_issue_writes_use_the_issue_client():
    # spec 5.7: the repository client (App token) never writes to the Release Issue
    gh, issues = repo(), FakeGitHub()

    act(plan("create-draft", trigger_type="pr_merge"), gh, MERGE_EVENT, issues)
    act(plan("reopen-issue", trigger_type="issue_close", command=""), gh, {}, issues)

    assert gh.releases and gh.comments == [] and gh.reopened == []
    assert [c["issue"] for c in issues.comments] == [40, 40] and issues.reopened == [40]


def test_clients_from_env(monkeypatch):
    monkeypatch.setenv("GITHUB_REPOSITORY", "camaraproject/Example")
    monkeypatch.setenv("GITHUB_TOKEN", "app-token")
    monkeypatch.setenv("ISSUE_TOKEN", "github-token")

    gh, issues = act_mod.clients_from_env()

    assert (gh.repo, gh.token, issues.repo, issues.token) == (
        "camaraproject/Example", "app-token", "camaraproject/Example", "github-token")


def test_clients_from_env_without_issue_token(monkeypatch):
    monkeypatch.setenv("GITHUB_REPOSITORY", "camaraproject/Example")
    monkeypatch.setenv("GITHUB_TOKEN", "github-token")
    monkeypatch.delenv("ISSUE_TOKEN", raising=False)

    gh, issues = act_mod.clients_from_env()

    assert gh.token == issues.token == "github-token"


