"""Tests for draft_release.py.

Expected values reproduce the former inline steps of
release-automation-reusable.yml: Extract CHANGELOG release notes and Create
Draft Release (handle-pr-merge), Discard Snapshot, Delete Draft Release and
both Cleanup review branch steps.
"""

import pytest

from release_automation.scripts import draft_release
from release_automation.scripts.draft_release import (
    CleanupOutcome,
    DraftOutcome,
    changelog_candidates,
    create_draft,
    delete_draft,
    discard_snapshot,
    extract_release_notes,
    prepare_changelog,
    preserve_review_branch,
    publish_on_merge,
    strip_candidate_block,
)
from release_automation.tests.fake_github import REPO_URL, FakeGitHub, gh_error

START = "<!-- BEGIN:AUTOGENERATED:CANDIDATE_CHANGES -->"
END = "<!-- END:AUTOGENERATED:CANDIDATE_CHANGES -->"
SNAPSHOT = "release-snapshot/r1.4-abc1234"
REVIEW = "release-review/r1.4-abc1234"
TIMEOUT = gh_error(
    "HTTP 409: Unable to validate rules for the branch. "
    "Rule was unable to be completed in 10 seconds"
)

CHANGELOG = (
    "# r1.4\n"
    "\n"
    "## Release Notes\n"
    "\n"
    "This release contains the definition and documentation of\n"
    "* Example v1.1.0\n"
    "\n"
    f"{START}\n"
    "candidate entries\n"
    f"{END}\n"
    "\n"
    "\n"
    "## Example v1.1.0\n"
    "\n"
    "* change\n"
    "\n"
    "\n"
    "# r1.3\n"
    "\n"
    "## Release Notes\n"
    "older\n"
)
STRIPPED = (
    "# r1.4\n"
    "\n"
    "## Release Notes\n"
    "\n"
    "This release contains the definition and documentation of\n"
    "* Example v1.1.0\n"
    "\n"
    "## Example v1.1.0\n"
    "\n"
    "* change\n"
    "\n"
    "# r1.3\n"
    "\n"
    "## Release Notes\n"
    "older\n"
)
NOTES = (
    "## Release Notes\n"
    "\n"
    "This release contains the definition and documentation of\n"
    "* Example v1.1.0\n"
    "\n"
    "## Example v1.1.0\n"
    "\n"
    "* change"
)
METADATA = "repository:\n  release_tag: r1.4\n  release_date: null\n"


@pytest.fixture(autouse=True)
def no_sleep(monkeypatch):
    slept = []
    monkeypatch.setattr(draft_release, "_sleep", slept.append)
    return slept


def snapshot_repo(changelog=CHANGELOG, path="CHANGELOG/CHANGELOG-r1.md", **kw):
    files = {(SNAPSHOT, "release-metadata.yaml"): METADATA}
    if changelog is not None:
        files[(SNAPSHOT, path)] = changelog
    return FakeGitHub(files=files, branches={SNAPSHOT: "s1", REVIEW: "v1", "main": "m1"}, **kw)


# ── CHANGELOG ────────────────────────────────────────────────────────────────


def test_changelog_candidates_prefer_the_cycle_file():
    assert changelog_candidates("r4.1") == ["CHANGELOG/CHANGELOG-r4.md"]
    assert changelog_candidates("unknown") == []


def test_strip_full_block_collapses_blank_runs():
    assert strip_candidate_block(CHANGELOG) == (STRIPPED, True)


@pytest.mark.parametrize("orphan", [START, END])
def test_strip_orphan_marker_line_only(orphan):
    text = f"# r1.4\n\n{orphan}\n\n\n## Release Notes\n"
    assert strip_candidate_block(text) == ("# r1.4\n\n\n\n## Release Notes\n", True)


def test_no_markers_is_unchanged():
    assert strip_candidate_block(STRIPPED) == (STRIPPED, False)


def test_markers_in_wrong_order_strip_the_start_marker():
    text = f"{END}\nx\n{START}\n"
    assert strip_candidate_block(text) == (f"{END}\nx\n", True)


def test_extract_release_notes_up_to_next_release_heading():
    assert extract_release_notes(STRIPPED) == NOTES


def test_extract_release_notes_heading_is_case_insensitive_and_runs_to_eof():
    assert extract_release_notes("# r1.4\n## release notes\nText\n\n\n") == "## release notes\nText"


def test_extract_release_notes_without_section():
    assert extract_release_notes("# r1.4\n## Example v1\n") == ""


def test_prepare_changelog_commits_the_stripped_file(capsys):
    gh = snapshot_repo()

    result = prepare_changelog(gh, "r1.4", SNAPSHOT)

    assert result.notes == NOTES and result.stripped
    assert gh.commits == [{
        "branch": SNAPSHOT, "path": "CHANGELOG/CHANGELOG-r1.md",
        "message": "chore: auto-remove candidate changes block from CHANGELOG", "sha": gh.commits[0]["sha"],
    }]
    assert gh.files[(SNAPSHOT, "CHANGELOG/CHANGELOG-r1.md")] == STRIPPED


def test_prepare_changelog_ignores_a_flat_changelog():
    gh = snapshot_repo(changelog=STRIPPED, path="CHANGELOG.md")

    result = prepare_changelog(gh, "r1.4", SNAPSHOT)

    assert (result.notes, result.stripped) == ("", False)
    assert gh.commits == []


def test_prepare_changelog_without_file_warns(capsys):
    result = prepare_changelog(snapshot_repo(changelog=None), "r1.4", SNAPSHOT)

    assert (result.notes, result.stripped) == ("", False)
    assert "::warning::No CHANGELOG file found on snapshot branch" in capsys.readouterr().out


def test_prepare_changelog_without_notes_section_warns(capsys):
    result = prepare_changelog(snapshot_repo(changelog="# r1.4\n"), "r1.4", SNAPSHOT)

    assert result.notes == ""
    assert '::warning::No "## Release Notes" section found in CHANGELOG/CHANGELOG-r1.md' in capsys.readouterr().out


def test_ruleset_timeout_on_the_commit_is_retried(no_sleep):
    gh = snapshot_repo(fail={"update_file": [TIMEOUT, TIMEOUT]})

    result = prepare_changelog(gh, "r1.4", SNAPSHOT)

    assert result.stripped and len(gh.commits) == 1
    assert no_sleep == [5, 10]


def test_ruleset_timeout_gives_up_after_two_retries():
    gh = snapshot_repo(fail={"update_file": [TIMEOUT, TIMEOUT, TIMEOUT]})

    with pytest.raises(draft_release.GitHubClientError):
        prepare_changelog(gh, "r1.4", SNAPSHOT)
    assert gh.commits == []


def test_other_commit_errors_are_not_retried(no_sleep):
    gh = snapshot_repo(fail={"update_file": [gh_error("HTTP 409: sha does not match")]})

    with pytest.raises(draft_release.GitHubClientError):
        prepare_changelog(gh, "r1.4", SNAPSHOT)
    assert no_sleep == []


# ── draft creation ───────────────────────────────────────────────────────────


def test_create_draft_from_changelog_notes():
    gh = snapshot_repo()

    outcome = create_draft(gh, "r1.4", SNAPSHOT, "pre-release-rc")

    release = gh.releases[0]
    assert outcome == DraftOutcome(success=True, draft_release_url=release["html_url"], candidate_block_stripped=True)
    assert (release["tag"], release["target"], release["name"]) == ("r1.4", SNAPSHOT, "r1.4")
    assert release["body"] == NOTES
    assert release["draft"] and release["prerelease"]
    assert "r1.4" not in gh.tags
    assert gh.calls.index("update_file") < gh.calls.index("create_release")


def test_create_draft_public_release_with_fallback_body():
    gh = snapshot_repo(changelog=None)

    outcome = create_draft(gh, "r1.4", SNAPSHOT, "public-release")

    assert outcome.success and not outcome.candidate_block_stripped
    assert not gh.releases[0]["prerelease"]
    assert gh.releases[0]["body"] == (
        "## Release r1.4\n\n**Release type:** public-release\n\n---\n\n"
        "_CHANGELOG.md content was not available — please add release notes manually._\n"
    )


def test_create_draft_failure(capsys):
    gh = snapshot_repo(fail={"create_release": [gh_error("HTTP 422: Validation Failed")]})

    outcome = create_draft(gh, "r1.4", SNAPSHOT, "pre-release-alpha")

    assert outcome == DraftOutcome(
        success=False, candidate_block_stripped=True,
        error_message="gh command failed: HTTP 422: Validation Failed",
    )
    assert "::error::Draft release creation failed: gh command failed: HTTP 422" in capsys.readouterr().out


def test_create_draft_changelog_commit_failure_creates_no_draft():
    gh = snapshot_repo(fail={"update_file": [gh_error("HTTP 403: protected")]})

    outcome = create_draft(gh, "r1.4", SNAPSHOT, "pre-release-alpha")

    assert not outcome.success
    assert outcome.error_message == "CHANGELOG cleanup failed: gh command failed: HTTP 403: protected"
    assert gh.releases == []


# ── discard and delete ───────────────────────────────────────────────────────


def test_discard_snapshot_closes_pr_deletes_snapshot_and_preserves_review():
    gh = snapshot_repo()

    outcome = discard_snapshot(gh, "24", SNAPSHOT, REVIEW)

    assert outcome == CleanupOutcome(success=True, renamed_review_branch=f"{REVIEW}-preserved")
    assert gh.closed_prs == [24]
    assert SNAPSHOT not in gh.branches and REVIEW not in gh.branches
    assert gh.branches[f"{REVIEW}-preserved"] == "v1"


def test_discard_snapshot_failure_keeps_review_branch(capsys):
    gh = snapshot_repo(fail={"close_pr": [gh_error("HTTP 404: Not Found")]})

    outcome = discard_snapshot(gh, "24", SNAPSHOT, REVIEW)

    assert outcome == CleanupOutcome(success=False, error_message="gh command failed: HTTP 404: Not Found")
    assert REVIEW in gh.branches and SNAPSHOT in gh.branches
    assert "::error::Discard failed: gh command failed: HTTP 404" in capsys.readouterr().out


def test_discard_without_pr_or_snapshot_branch_only_preserves_review():
    gh = snapshot_repo()

    outcome = discard_snapshot(gh, "", "", REVIEW)

    assert outcome.success and gh.closed_prs == [] and SNAPSHOT in gh.branches
    assert outcome.renamed_review_branch == f"{REVIEW}-preserved"


def test_missing_snapshot_branch_fails_the_discard():
    gh = snapshot_repo()
    del gh.branches[SNAPSHOT]

    outcome = discard_snapshot(gh, "24", SNAPSHOT, REVIEW)

    assert not outcome.success
    assert outcome.error_message == f"Snapshot branch {SNAPSHOT} not found"


def test_delete_draft_deletes_release_tag_and_snapshot():
    gh = snapshot_repo(releases=[{"id": 7, "tag": "r1.4", "target": SNAPSHOT, "draft": True, "prerelease": True, "html_url": "u"}])
    gh.tags["r1.4"] = "s1"

    outcome = delete_draft(gh, "r1.4", SNAPSHOT, REVIEW)

    assert outcome == CleanupOutcome(success=True, renamed_review_branch=f"{REVIEW}-preserved")
    assert gh.releases == [] and "r1.4" not in gh.tags and SNAPSHOT not in gh.branches


def test_delete_draft_without_draft_or_tag_still_cleans_up(capsys):
    gh = snapshot_repo()

    outcome = delete_draft(gh, "r1.4", SNAPSHOT, REVIEW)

    assert outcome.success and SNAPSHOT not in gh.branches
    out = capsys.readouterr().out
    assert "Warning: No draft release found for tag r1.4" in out
    assert "Tag r1.4 not found or already deleted" in out


def test_delete_draft_tag_error_is_logged_not_fatal(capsys):
    gh = snapshot_repo(fail={"delete_tag": [gh_error("HTTP 500")]})

    assert delete_draft(gh, "r1.4", SNAPSHOT, REVIEW).success


def test_delete_draft_release_error_fails(capsys):
    gh = snapshot_repo(
        releases=[{"id": 7, "tag": "r1.4", "target": SNAPSHOT, "draft": True, "prerelease": True, "html_url": "u"}],
        fail={"delete_release": [gh_error("HTTP 403")]},
    )

    outcome = delete_draft(gh, "r1.4", SNAPSHOT, REVIEW)

    assert outcome == CleanupOutcome(success=False, error_message="gh command failed: HTTP 403")
    assert "::error::Delete draft failed: gh command failed: HTTP 403" in capsys.readouterr().out


def test_preserve_review_branch_replaces_an_older_preserved_copy(capsys):
    gh = snapshot_repo()
    gh.branches[f"{REVIEW}-preserved"] = "old"

    assert preserve_review_branch(gh, REVIEW) == f"{REVIEW}-preserved"
    assert gh.branches[f"{REVIEW}-preserved"] == "v1"
    out = capsys.readouterr().out
    assert f"Deleted previous {REVIEW}-preserved" in out
    assert f"Renamed: {REVIEW} → {REVIEW}-preserved" in out


def test_preserve_missing_review_branch_leaves_preserved_copy(capsys):
    gh = snapshot_repo()
    del gh.branches[REVIEW]
    gh.branches[f"{REVIEW}-preserved"] = "old"

    assert preserve_review_branch(gh, REVIEW) == ""
    assert gh.branches[f"{REVIEW}-preserved"] == "old"
    assert f"Could not rename review branch: {REVIEW} not found" in capsys.readouterr().out


def test_preserve_rename_error_is_logged():
    gh = snapshot_repo(fail={"create_branch_at_sha": [gh_error("HTTP 403")]})

    assert preserve_review_branch(gh, REVIEW) == ""


def test_preserve_without_review_branch_is_a_no_op():
    gh = snapshot_repo()

    assert preserve_review_branch(gh, "") == ""
    assert gh.calls == []


# ── publish on merge ─────────────────────────────────────────────────────────


def test_publish_on_merge_commits_changelog_then_release_date_then_tags():
    gh = snapshot_repo()

    outcome = publish_on_merge(gh, "r1.4", SNAPSHOT, REVIEW, "pre-release-rc", "abc1234def")

    assert [c["path"] for c in gh.commits] == ["CHANGELOG/CHANGELOG-r1.md", "release-metadata.yaml"]
    release = gh.releases[0]
    assert not release["draft"] and release["prerelease"] and release["make_latest"] == "false"
    assert release["body"] == NOTES and release["target"] == SNAPSHOT
    # The tag is at the release_date commit, which follows the CHANGELOG cleanup.
    assert gh.tags["r1.4"] == gh.commits[1]["sha"]
    assert "release_date: '20" in gh.files[(SNAPSHOT, "release-metadata.yaml")]
    assert outcome.success
    assert outcome.release_url == f"{REPO_URL}/releases/tag/r1.4"
    assert outcome.reference_tag == "source/r1.4" and gh.tags["source/r1.4"] == "abc1234def"
    assert outcome.pointer_branch == "pre-release/r1.4"
    assert gh.branches["pre-release/r1.4"] == gh.tags["r1.4"]
    assert SNAPSHOT not in gh.branches and REVIEW not in gh.branches
    assert outcome.error_message == ""


def test_publish_on_merge_public_release_is_latest():
    gh = snapshot_repo()

    outcome = publish_on_merge(gh, "r1.4", SNAPSHOT, REVIEW, "public-release", "abc1234def")

    assert gh.releases[0]["make_latest"] == "true" and not gh.releases[0]["prerelease"]
    assert outcome.pointer_branch == "release/r1.4"


def test_publish_on_merge_keeps_latest_of_a_later_cycle():
    gh = snapshot_repo(releases=[{
        "id": 1, "tag": "r2.1", "draft": False, "prerelease": False, "html_url": f"{REPO_URL}/releases/tag/r2.1",
    }])

    publish_on_merge(gh, "r1.4", SNAPSHOT, REVIEW, "maintenance-release", "abc1234def")

    assert gh.releases[-1]["tag"] == "r1.4" and gh.releases[-1]["make_latest"] == "false"


def test_publish_on_merge_failure_before_tag():
    gh = snapshot_repo(fail={"create_release": [gh_error("HTTP 422: tag protected")]})

    outcome = publish_on_merge(gh, "r1.4", SNAPSHOT, REVIEW, "pre-release-rc", "abc1234def")

    assert not outcome.success
    assert outcome.error_message == "Failed to publish release: gh command failed: HTTP 422: tag protected"
    assert SNAPSHOT in gh.branches and "source/r1.4" not in gh.tags


def test_publish_on_merge_changelog_failure_does_not_publish():
    gh = snapshot_repo(fail={"update_file": [gh_error("HTTP 403")]})

    outcome = publish_on_merge(gh, "r1.4", SNAPSHOT, REVIEW, "pre-release-rc", "abc1234def")

    assert not outcome.success and outcome.error_message.startswith("CHANGELOG cleanup failed")
    assert gh.releases == []
